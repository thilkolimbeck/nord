#!/usr/bin/env python3
"""Generate the Stage 4 editor's display tables and its label golden from nordconv.

Why a second generator: the converter's TypeScript tables (web/src/engine/generated/
tables-ns4.ts) hold only what the conversion reads. The editor needs every display table
(value, enum and dependency tables, port names) to label, range and format the controls.
Those already live in nordconv/_tables_ns4.py, written by tools/gen_layouts.py from
opennord, so this script needs no opennord checkout and leaves every existing generated
file untouched.

Usage:
    python3 -I tools/gen_editor_tables.py [--check]

Writes web/src/editor/generated/display-ns4.ts (the tables and NS4_KEYS, the layout keys in
layout order) and web/test/editor/labels-golden.json (nordconv.labels.ns4_label for every
value of every field a table covers: the reference the editor's own label port is tested
against). --check writes nothing and exits 1 when a committed file differs from a fresh render.
Standard library only.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / 'tools'))

import gen_layouts  # noqa: E402  (licence header and the TS comment form shared with the main generator)
from nordconv import _tables_ns4 as t  # noqa: E402
from nordconv.labels import ns4_label  # noqa: E402
from nordconv.layout import NS4_LAYOUT  # noqa: E402
from nordconv.template import load_template  # noqa: E402

TS_OUT = ROOT / 'web' / 'src' / 'editor' / 'generated' / 'display-ns4.ts'
GOLDEN_OUT = ROOT / 'web' / 'test' / 'editor' / 'labels-golden.json'
TABLES_SOURCE = ROOT / 'nordconv' / '_tables_ns4.py'
# Fields with a wider range have no table (delay tempo, name hashes); the golden skips them.
MAX_GOLDEN_RANGE = 1024


def _ts(obj: Any) -> str:
    return json.dumps(obj, ensure_ascii=False)


def source_commit() -> str:
    """The opennord commit nordconv/_tables_ns4.py was generated from (its header says)."""
    m = re.search(r'^# at commit (\w+)\.', TABLES_SOURCE.read_text(encoding='utf-8'), re.M)
    return m.group(1) if m else 'unknown'


def header() -> str:
    text = gen_layouts.LICENCE_HEADER.format(source='tables, via nordconv/_tables_ns4.py',
                                             commit=source_commit(), extra=gen_layouts.MIT_NOTICE)
    text = text.replace('# GENERATED by tools/gen_layouts.py', '# GENERATED by tools/gen_editor_tables.py')
    return gen_layouts.ts_header(text)


def _pairs(table: Dict[int, str]) -> List[List[Any]]:
    return [[raw, label] for raw, label in table.items()]


def render_ts() -> str:
    """web/src/editor/generated/display-ns4.ts."""
    used_value = {pid for pid, _ in t.FIELD_VALUE_TABLE.values()}
    used_enum = {name for name, _ in t.FIELD_ENUM.values()}
    used_dep = {pid for pid, _, _ in t.FIELD_DEP.values()}
    lines = [header(), '/** Nord Stage 4 display tables for the editor, keyed to firmware layout fields. */', '']
    lines += ['/** Every layout key, in layout order (nordconv/_layout_ns4.py FIELDS). */',
              'export const NS4_KEYS = [']
    lines += [f'  {_ts(key)},' for key in NS4_LAYOUT.fields]
    lines += ['] as const;', '']

    def record(comment: str, decl: str, items: List[Any]) -> None:
        lines.append(f'/** {comment} */')
        lines.append(f'{decl} = {{')
        lines.extend(f'  {_ts(k)}: {_ts(v)},' for k, v in items)
        lines.extend(['};', ''])

    record('ns4decode port param id -> [raw, display string] pairs in raw order (opennord values.generated.ts).',
           'export const VALUE_TABLES: Readonly<Record<string, ReadonlyArray<readonly [number, string]>>>',
           [(pid, _pairs(table)) for pid, table in t.VALUE_TABLES.items() if pid in used_value])
    record('Firmware field key -> [port param id, port width].',
           'export const FIELD_VALUE_TABLE: Readonly<Record<string, readonly [string, number]>>',
           [(k, list(v)) for k, v in t.FIELD_VALUE_TABLE.items()])
    record('Enum name -> [raw, display string] pairs (opennord interpret.generated.ts).',
           'export const ENUM_TABLES: Readonly<Record<string, ReadonlyArray<readonly [number, string]>>>',
           [(name, _pairs(table)) for name, table in t.ENUM_TABLES.items() if name in used_enum])
    record('Firmware field key -> [enum name, port width].',
           'export const FIELD_ENUM: Readonly<Record<string, readonly [string, number]>>',
           [(k, list(v)) for k, v in t.FIELD_ENUM.items()])
    lines += ['/** Port param id -> {"dep1:dep2:...:raw": label}: tables whose label depends on other fields',
              ' * (keyboard zones on the split points, osc category and wave on the osc bank; opennord',
              ' * deps.generated.ts). */',
              'export const DEP_TABLES: Readonly<Record<string, Readonly<Record<string, string>>>> = {']
    for pid, table in t.DEP_TABLES.items():
        if pid not in used_dep:
            continue
        lines.append(f'  {_ts(pid)}: {{')
        lines.extend(f'    {_ts(k)}: {_ts(v)},' for k, v in table.items())
        lines.append('  },')
    lines += ['};', '']
    record('Firmware field key -> [port param id, port width, dependency field keys in key order].',
           'export const FIELD_DEP: Readonly<Record<string, readonly [string, number, readonly string[]]>>',
           [(k, [pid, width, list(deps)]) for k, (pid, width, deps) in t.FIELD_DEP.items()])
    record('ns4decode port param id -> parameter name (opennord values.generated.ts).',
           'export const PORT_NAMES: Readonly<Record<string, string>>',
           list(t.PORT_NAMES.items()))
    return '\n'.join(lines)


def _labels(program: Any, key: str) -> List[Optional[str]]:
    f = NS4_LAYOUT.fields[key]
    out: List[Optional[str]] = []
    for value in range(f.min, f.max + 1):
        program.set(key, value)
        out.append(ns4_label(program, key))
    return out


def _dep_rows(program: Any, deps: List[str]) -> List[List[int]]:
    rows: List[List[int]] = [[]]
    for dep in deps:
        f = NS4_LAYOUT.fields[dep]
        rows = [row + [v] for row in rows for v in range(f.min, f.max + 1)]
    return rows


def render_golden() -> str:
    """web/test/editor/labels-golden.json: Python's labels for every value of every tabled field.

    A plain field maps to {"min": first value, "labels": [label or null per value]}; a field with
    a dependency table maps to {"deps": [dep keys], "rows": {"<dep values joined by :>": [...]}},
    with the dependency values as stored (decoded), not as raw bits.
    """
    program = load_template()
    covered = set(t.FIELD_VALUE_TABLE) | set(t.FIELD_ENUM) | set(t.FIELD_DEP)
    fields: List[str] = []
    for key, f in NS4_LAYOUT.fields.items():
        if key not in covered:
            continue
        if f.enc == 'raw' or f.max - f.min > MAX_GOLDEN_RANGE:
            raise ValueError(f'{key}: a table covers a field with range {f.min}..{f.max}')
        if key in t.FIELD_DEP:
            deps = list(t.FIELD_DEP[key][2])
            rows: Dict[str, List[Optional[str]]] = {}
            for row in _dep_rows(program, deps):
                for dep, value in zip(deps, row):
                    program.set(dep, value)
                rows[':'.join(str(v) for v in row)] = _labels(program, key)
            entry: Dict[str, Any] = {'deps': deps, 'rows': rows}
        else:
            entry = {'min': f.min, 'labels': _labels(program, key)}
        fields.append(f'    {_ts(key)}: {json.dumps(entry, ensure_ascii=False, separators=(",", ":"))}')
    lines = ['{',
             '  "source": "nordconv.labels.ns4_label, written by tools/gen_editor_tables.py",',
             '  "fields": {',
             ',\n'.join(fields),
             '  }',
             '}',
             '']
    return '\n'.join(lines)


def outputs() -> Dict[Path, str]:
    return {TS_OUT: render_ts(), GOLDEN_OUT: render_golden()}


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true', help='compare with the committed files, write nothing')
    args = ap.parse_args(argv)
    stale = []
    for path, text in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != text:
                stale.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding='utf-8')
        print(f'wrote {path.relative_to(ROOT)} ({len(text)} bytes)')
    for path in stale:
        print(f'stale: {path.relative_to(ROOT)} (run npm run gen:editor)', file=sys.stderr)
    return 1 if stale else 0


if __name__ == '__main__':
    sys.exit(main())
