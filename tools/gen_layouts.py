# ---------------------------------------------------------------- TS literal parser

TOKEN_RE = re.compile(r'''
    (?P<ws>\s+|//[^\n]*|/\*.*?\*/)
  | (?P<str>'(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*")
  | (?P<num>-?\d+(?:\.\d+)?)
  | (?P<spread>\.\.\.)
  | (?P<ident>[A-Za-z_$][\w$]*)
  | (?P<punct>[{}\[\]:,])
''', re.S | re.X)

ESCAPES = {'n': '\n', 't': '\t', "'": "'", '"': '"', '\\': '\\'}


def _tokens(text: str, pos: int) -> Iterator[Tuple[str, str, int]]:
    """Yield (kind, text, end) from `pos`, skipping whitespace and comments."""
    while pos < len(text):
        m = TOKEN_RE.match(text, pos)
        if not m:
            raise ValueError(f'unexpected character {text[pos]!r} at {pos}')
        pos = m.end()
        if m.lastgroup != 'ws':
            yield m.lastgroup, m.group(), pos


def _unquote(s: str) -> str:
    return re.sub(r'\\(.)', lambda m: ESCAPES.get(m.group(1), m.group(1)), s[1:-1])


class _Parser:
    """Recursive-descent reader for the object/array literals opennord generates."""

    def __init__(self, text: str, pos: int, consts: Dict[str, Any]):
        self.toks = _tokens(text, pos)
        self.consts = consts
        self.peeked: Optional[Tuple[str, str, int]] = None

    def next(self) -> Tuple[str, str, int]:
        if self.peeked is not None:
            tok, self.peeked = self.peeked, None
            return tok
        return next(self.toks)

    def peek(self) -> Tuple[str, str, int]:
        if self.peeked is None:
            self.peeked = next(self.toks)
        return self.peeked

    def value(self) -> Any:
        kind, text, _ = self.next()
        if kind == 'str':
            return _unquote(text)
        if kind == 'num':
            return float(text) if '.' in text else int(text)
        if kind == 'ident':
            if text in ('true', 'false'):
                return text == 'true'
            if text == 'null':
                return None
            raise ValueError(f'identifier {text!r} is not a literal')
        if text == '[':
            return self._array()
        if text == '{':
            return self._object()
        raise ValueError(f'unexpected token {text!r}')

    def _array(self) -> List[Any]:
        out: List[Any] = []
        while True:
            if self.peek()[1] == ']':
                self.next()
                return out
            if self.peek()[0] == 'spread':
                self.next()
                out.extend(self.consts[self.next()[1]])
            else:
                out.append(self.value())
            if self.next()[1] == ']':
                return out

    def _object(self) -> Dict[Any, Any]:
        out: Dict[Any, Any] = {}
        while True:
            kind, text, _ = self.next()
            if text == '}':
                return out
            key: Any = _unquote(text) if kind == 'str' else int(text) if kind == 'num' else text
            if self.next()[1] != ':':
                raise ValueError(f'expected ":" after key {key!r}')
            out[key] = self.value()
            if self.next()[1] == '}':
                return out


CONST_RE = re.compile(r'^(?:export )?const (\w+)\s*(?::[^=\n]*)?=\s*(?=[\[{])', re.M)


def parse_ts_consts(path: Path) -> Dict[str, Any]:
    """Every top-level `const NAME = <literal>` of a TS file whose literal parses.

    Consts that are not pure literals (a `new Map(...)`, a function result,
    a literal holding identifiers) are skipped: the generated modules only carry
    data.
    """
    text = path.read_text(encoding='utf-8')
    consts: Dict[str, Any] = {}
    for m in CONST_RE.finditer(text):
        try:
            consts[m.group(1)] = _Parser(text, m.end(), consts).value()
        except (ValueError, KeyError, StopIteration):
            continue
    return consts


# ---------------------------------------------------------------- layouts

def _layout_const(consts: Dict[str, Any]) -> Dict[str, Any]:
    (layout,) = [v for k, v in consts.items() if k.endswith('_LAYOUT')]
    return layout


def render_layout(layout: Dict[str, Any], header: str) -> str:
    """Python source for one model's layout, as plain tuples (cheap to import)."""
    keys = [f['key'] for f in layout['fields']]
    if len(keys) != len(set(keys)):
        raise SystemExit('duplicate field keys in layout')
    blocks = tuple((b['key'], b['name'], b['offset'], b['length']) for b in layout['blocks'])
    fields = tuple((f['key'], f['name'], f['block'], f['bit'], f['width'], f['min'], f['max'], f['def'], f['enc'],
                    f['confidence'])
                   for f in layout['fields'])
    lines = [header,
             f'"""{layout["model"]} program layout: blocks and bit fields of the body."""',
             '',
             f'MODEL = {layout["model"]!r}',
             f'SOURCE = {layout["source"]!r}',
             f'CONTAINER = {layout["container"]!r}',
             f'VERSION_RANGE = {tuple(layout["versionRange"])!r}',
             f'BODY_BYTES = {layout["bodyBytes"]!r}',
             '',
             '# (key, firmware name, body offset of the length byte, payload length)',
             'BLOCKS = (']
    lines += [f'    {b!r},' for b in blocks]
    lines += [')', '',
              '# (key, firmware name, block index, bit in block payload, width, min, max, default, encoding,',
              '#  confidence). Encodings: u = unsigned; offset = raw + min; twos = two\'s complement;',
              '#  raw = opaque 32-bit hash. Confidence is the source layout\'s: high or medium.',
              'FIELDS = (']
    lines += [f'    {f!r},' for f in fields]
    lines += [')', '']
    return '\n'.join(lines)


def field_file_bits(layout: Dict[str, Any]) -> Dict[str, Tuple[int, int]]:
    """Field key -> (first, last) absolute file bit, the addressing ns4decode's map uses."""
    out = {}
    for f in layout['fields']:
        beg = CBIN_BODY_OFFSET * 8 + (layout['blocks'][f['block']]['offset'] + 1) * 8 + f['bit']
        out[f['key']] = (beg, beg + f['width'] - 1)
    return out


# ---------------------------------------------------------------- NS4 tables

def port_to_fields(offset_map: List[Dict[str, Any]], layout: Dict[str, Any]) -> Dict[str, List[Optional[Tuple[str, int]]]]:
    """Port param id -> per layer (firmware field key, port width) or None.

    A port layer maps to a firmware field when it covers exactly the same bits,
    or when it reads the field's low bits and no other port param reads any part
    of that field (the synth osc knobs). Bitmask fields read through several
    port params (layer on/off, mono/legato) never map, because one param's
    table does not describe the whole field.
    """
    bits = field_file_bits(layout)
    by_end = {}
    for key, (beg, end) in bits.items():
        by_end.setdefault(end, []).append((key, beg))
    claims: Dict[str, int] = {}
    for p in offset_map:
        for layer in p['layers']:
            for key, (beg, end) in bits.items():
                if layer['begBit'] <= end and layer['endBit'] >= beg:
                    claims[key] = claims.get(key, 0) + 1
    out: Dict[str, List[Optional[Tuple[str, int]]]] = {}
    for p in offset_map:
        mapped: List[Optional[Tuple[str, int]]] = []
        for layer in p['layers']:
            width = layer['endBit'] - layer['begBit'] + 1
            hit = None
            for key, beg in by_end.get(layer['endBit'], []):
                if beg == layer['begBit'] or (beg < layer['begBit'] and claims[key] == 1):
                    hit = (key, width)
            mapped.append(hit)
        out[p['id']] = mapped
    return out


def ns4_table_data(ref: Path, layout: Dict[str, Any]) -> Dict[str, Any]:
    """The Stage 4 display tables keyed to layout fields, shared by the Python and TS renderers."""
    lib = ref / 'src/lib/ns4'
    values = parse_ts_consts(lib / 'values.generated.ts')['GENERATED_VALUES']
    interp = parse_ts_consts(lib / 'interpret.generated.ts')
    deps = parse_ts_consts(lib / 'deps.generated.ts')
    analog = parse_ts_consts(lib / 'synth-analog.generated.ts')
    names = parse_ts_consts(lib / 'names.generated.ts')
    offset_map = parse_ts_consts(lib / 'offset-map.generated.ts')['NS4_OFFSET_MAP']
    mapping = port_to_fields(offset_map, layout)
    port_by_id = {p['id']: p for p in offset_map}

    field_value: Dict[str, Tuple[str, int]] = {}
    field_enum: Dict[str, Tuple[str, int]] = {}
    for p in offset_map:
        for hit in mapping[p['id']]:
            if hit is None:
                continue
            key, width = hit
            if p['id'] in values:
                field_value[key] = (p['id'], width)
            if p['name'] in interp['PARAM_TABLE']:
                field_enum[key] = (interp['PARAM_TABLE'][p['name']], width)
    value_tables = {pid: values[pid] for pid in sorted({pid for pid, _ in field_value.values()})}

    dep_tables = {pid: dict(deps['DEP_TABLES'][pid]) for pid in DEP_PORT_IDS}
    dep_tables['561-8'] = {**analog['ANALOG_CAT_561_8'], **dep_tables['561-8']}
    dep_tables['562-4'] = {**analog['ANALOG_WAVE_562_4'], **dep_tables['562-4']}
    field_dep: Dict[str, Tuple[str, int, Tuple[str, ...]]] = {}
    for pid in DEP_PORT_IDS:
        for layer, hit in enumerate(mapping[pid]):
            if hit is None:
                raise SystemExit(f'dependency param {pid} layer {layer} has no firmware field')
            dep_keys = []
            for did in deps['DEP_IDS'][pid]:
                dep_layers = mapping[did]
                dep_hit = dep_layers[layer] if layer < len(dep_layers) else dep_layers[0]
                if dep_hit is None:
                    raise SystemExit(f'dependency {did} of {pid} has no firmware field')
                dep_keys.append(dep_hit[0])
            field_dep[hit[0]] = (pid, hit[1], tuple(dep_keys))

    port_names = {pid: port_by_id[pid]['name'] for pid in sorted(set(value_tables) | set(dep_tables))}
    return {'value_tables': value_tables, 'field_value': field_value, 'enum_tables': interp['ENUM_TABLES'],
            'field_enum': field_enum, 'dep_tables': dep_tables, 'field_dep': field_dep, 'port_names': port_names,
            'piano_names': names['PIANO_NAMES'], 'sample_names': names['SAMPLE_NAMES']}


def render_tables_ns4(ref: Path, layout: Dict[str, Any], header: str) -> str:
    data = ns4_table_data(ref, layout)
    value_tables, field_value, field_enum = data['value_tables'], data['field_value'], data['field_enum']
    dep_tables, field_dep, port_names = data['dep_tables'], data['field_dep'], data['port_names']

    def block(name: str, comment: str, obj: Any) -> List[str]:
        return [f'# {line}' if line else '#' for line in comment.splitlines()] + \
               [f'{name} = ' + pprint.pformat(obj, width=110, compact=True, sort_dicts=True), '']

    lines = [header,
             '"""Nord Stage 4 display tables, keyed to firmware layout fields."""',
             '']
    lines += block('VALUE_TABLES', 'ns4decode port param id -> {raw: display string} (opennord values.generated.ts).',
                   value_tables)
    lines += block('FIELD_VALUE_TABLE',
                   'Firmware field key -> (port param id, port width). A raw at or above 2**width has no entry.',
                   field_value)
    lines += block('ENUM_TABLES', 'Enum name -> {raw: label} (opennord interpret.generated.ts).',
                   data['enum_tables'])
    lines += block('FIELD_ENUM', 'Firmware field key -> (enum name, port width).', field_enum)
    lines += block('DEP_TABLES',
                   'Port param id -> {"dep1:dep2:...:raw": label}, for the params whose label depends on\n'
                   'other fields (opennord deps.generated.ts, plus synth-analog.generated.ts for osc bank 0).',
                   dep_tables)
    lines += block('FIELD_DEP',
                   'Firmware field key -> (port param id, port width, dependency field keys in key order).\n'
                   'Each layer reads its own dependencies; single-layer ones (the split points) are shared.',
                   field_dep)
    lines += block('PORT_NAMES', 'Port param id -> ns4decode parameter name, for messages.', port_names)
    lines += block('PIANO_NAMES', 'Stage 4 piano model hash -> name (opennord names.generated.ts).',
                   data['piano_names'])
    lines += block('SAMPLE_NAMES', 'Stage 4 sample hash -> name (opennord names.generated.ts).',
                   data['sample_names'])
    return '\n'.join(lines)


# ---------------------------------------------------------------- NS3 tables

NS3_TABLE_SOURCES = (
    ('src/lib/ns3/decode.ts', None),
    ('src/lib/ns3/filter-freq.ts', None),
    ('src/lib/clavia/volume.ts', ('NORD_DB',)),
    ('src/lib/clavia/fx-tables.ts', ('EQ_MID_FREQ', 'EFFECT_SRC')),
)


def render_tables_ns3(ref: Path, header: str) -> str:
    lines = [header, '"""Nord Stage 3 label tables (opennord ns3/decode.ts and the clavia tables it imports)."""', '']
    for rel, wanted in NS3_TABLE_SOURCES:
        consts = parse_ts_consts(ref / rel)
        lines.append(f'# ---- from {rel}')
        for name in (wanted or sorted(consts)):
            lines.append(f'{name} = ' + pprint.pformat(consts[name], width=110, compact=True, sort_dicts=True))
        lines.append('')
    return '\n'.join(lines)


# ---------------------------------------------------------------- TypeScript (web engine)

# The TS engine (web/src/engine) needs only what the converter reads: the two layouts (without the
# firmware names and confidence), the Stage 3 label tables the mapping uses, the Stage 4 split-note
# table, the keyboard-zone dependency tables and the piano model hashes (membership only).
TS_NS3_TABLES = ('ADDED_IN', 'KB_ZONES', 'OSC_CLASSIC_WAVE', 'OSC_CONFIG', 'OSC_SUPER_WAVE', 'PIANO_TYPE',
                 'SPLIT_NOTE', 'SYNTH_OSC')
TS_VALUE_FIELDS = ('common.splitPosLow',)
TS_DEP_PORT_IDS = ('113-1', '243-1', '414-3')


def _ts(obj: Any) -> str:
    return json.dumps(obj, ensure_ascii=False)


def ts_header(header: str) -> str:
    """The Python licence header as // comments."""
    return '\n'.join('//' + line[1:] if line.startswith('#') else line for line in header.splitlines()) + '\n'


def render_ts_layout(layout: Dict[str, Any], header: str) -> str:
    lines = [ts_header(header),
             f'/** {layout["model"]} program layout: blocks and bit fields of the body. */',
             '',
             f'export const MODEL = {_ts(layout["model"])};',
             f'export const VERSION_RANGE: readonly [number, number] = {_ts(list(layout["versionRange"]))};',
             f'export const BODY_BYTES = {_ts(layout["bodyBytes"])};',
             '',
             '/** [key, body offset of the length byte, payload length] */',
             'export const BLOCKS: ReadonlyArray<readonly [string, number, number]> = [']
    lines += [f'  {_ts([b["key"], b["offset"], b["length"]])},' for b in layout['blocks']]
    lines += ['];', '',
              '/**',
              ' * [key, block index, bit in block payload, width, min, max, default, encoding], in layout order.',
              " * Encodings: u = unsigned; offset = raw + min; twos = two's complement; raw = opaque 32-bit hash.",
              ' */',
              'export const FIELDS: ReadonlyArray<',
              '  readonly [string, number, number, number, number, number, number, string]',
              '> = [']
    lines += [f'  {_ts([f["key"], f["block"], f["bit"], f["width"], f["min"], f["max"], f["def"], f["enc"]])},'
              for f in layout['fields']]
    lines += ['];', '']
    return '\n'.join(lines)


def render_ts_tables_ns3(ref: Path, header: str) -> str:
    consts = parse_ts_consts(ref / 'src/lib/ns3/decode.ts')
    lines = [ts_header(header), '/** Nord Stage 3 label tables the converter reads (opennord ns3/decode.ts). */', '']
    for name in TS_NS3_TABLES:
        value = consts[name]
        if name == 'ADDED_IN':
            kind = 'ReadonlyArray<{ readonly before: number; readonly keys: readonly string[] }>'
        else:
            kind = 'readonly string[]'
        lines.append(f'export const {name}: {kind} = {_ts(value)};')
    lines.append('')
    return '\n'.join(lines)


def render_ts_tables_ns4(data: Dict[str, Any], header: str) -> str:
    field_value = {k: list(data['field_value'][k]) for k in TS_VALUE_FIELDS}
    value_tables = {pid: [[raw, label] for raw, label in sorted(data['value_tables'][pid].items())]
                    for pid in sorted({pid for pid, _ in field_value.values()})}
    field_dep = {k: [pid, width, list(deps)] for k, (pid, width, deps) in sorted(data['field_dep'].items())
                 if pid in TS_DEP_PORT_IDS}
    dep_tables = {pid: dict(sorted(data['dep_tables'][pid].items())) for pid in TS_DEP_PORT_IDS}

    def block(comment: str, decl: str, obj: Any, rows: bool = True) -> List[str]:
        out = [f'/** {comment} */']
        if rows and isinstance(obj, dict):
            out.append(f'{decl} = {{')
            out += [f'  {_ts(k)}: {_ts(v)},' for k, v in obj.items()]
            out.append('};')
        elif rows:
            out.append(f'{decl} = [')
            out += [f'  {_ts(v)},' for v in obj]
            out.append('];')
        else:
            out.append(f'{decl} = {_ts(obj)};')
        return out + ['']

    lines = [ts_header(header), '/** Nord Stage 4 tables the converter reads, keyed to firmware layout fields. */', '']
    lines += block('ns4decode port param id -> [raw, display string] pairs in raw order (opennord '
                   'values.generated.ts).',
                   'export const VALUE_TABLES: Readonly<Record<string, ReadonlyArray<readonly [number, string]>>>',
                   value_tables)
    lines += block('Firmware field key -> [port param id, port width].',
                   'export const FIELD_VALUE_TABLE: Readonly<Record<string, readonly [string, number]>>',
                   field_value)
    lines += ['/** Port param id -> {"dep1:dep2:...:raw": label}: the keyboard zones, whose label depends on the',
              ' * split points (opennord deps.generated.ts). */',
              'export const DEP_TABLES: Readonly<Record<string, Readonly<Record<string, string>>>> = {']
    for pid, table in dep_tables.items():
        lines.append(f'  {_ts(pid)}: {{')
        lines += [f'    {_ts(k)}: {_ts(v)},' for k, v in table.items()]
        lines.append('  },')
    lines += ['};', '']
    lines += block('Firmware field key -> [port param id, port width, dependency field keys in key order].',
                   'export const FIELD_DEP: Readonly<Record<string, readonly [string, number, readonly string[]]>>',
                   field_dep)
    lines += block('Stage 4 piano model hashes (opennord names.generated.ts PIANO_NAMES keys).',
                   'export const PIANO_NAME_HASHES: readonly number[]', sorted(data['piano_names']), rows=False)
    return '\n'.join(lines)

# ---------------------------------------------------------------- main

def short_commit(ref: Path) -> str:
    try:
        return subprocess.run(['git', '-C', str(ref), 'rev-parse', '--short=7', 'HEAD'],
                              check=True, capture_output=True, text=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return 'unknown'


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('opennord', type=Path, help='path to an opennord checkout (read only)')
    ap.add_argument('--out', type=Path, default=Path(__file__).resolve().parent.parent / 'nordconv')
    ap.add_argument('--ts-out', type=Path,
                    default=Path(__file__).resolve().parent.parent / 'web' / 'src' / 'engine' / 'generated')
    args = ap.parse_args(argv)
    ref: Path = args.opennord
    commit = short_commit(ref)
    if commit != PINNED_COMMIT:
        print(f'warning: opennord is at {commit}, the tables were reviewed at {PINNED_COMMIT}', file=sys.stderr)

    def header(source: str, mit: bool = False) -> str:
        return LICENCE_HEADER.format(source=source, commit=commit, extra=MIT_NOTICE if mit else '')

    ns3 = _layout_const(parse_ts_consts(ref / 'src/lib/ns3/layout.generated.ts'))
    ns4 = _layout_const(parse_ts_consts(ref / 'src/lib/ns4/layout.generated.ts'))
    outputs = {
        '_layout_ns3.py': render_layout(ns3, header('src/lib/ns3/layout.generated.ts')),
        '_layout_ns4.py': render_layout(ns4, header('src/lib/ns4/layout.generated.ts', mit=True)),
        '_tables_ns3.py': render_tables_ns3(ref, header('src/lib/ns3/decode.ts, ns3/filter-freq.ts, '
                                                        'clavia/volume.ts, clavia/fx-tables.ts')),
        '_tables_ns4.py': render_tables_ns4(ref, ns4, header(
            'src/lib/ns4/values.generated.ts, interpret.generated.ts, deps.generated.ts,\n'
            '# synth-analog.generated.ts, names.generated.ts and offset-map.generated.ts', mit=True)),
    }
    ns4_source = 'src/lib/ns4/values.generated.ts, deps.generated.ts, names.generated.ts\n# and offset-map.generated.ts'
    ts_outputs = {
        'layout-ns3.ts': render_ts_layout(ns3, header('src/lib/ns3/layout.generated.ts')),
        'layout-ns4.ts': render_ts_layout(ns4, header('src/lib/ns4/layout.generated.ts', mit=True)),
        'tables-ns3.ts': render_ts_tables_ns3(ref, header('src/lib/ns3/decode.ts')),
        'tables-ns4.ts': render_ts_tables_ns4(ns4_table_data(ref, ns4), header(ns4_source, mit=True)),
    }
    for out_dir, texts in ((args.out, outputs), (args.ts_out, ts_outputs)):
        out_dir.mkdir(parents=True, exist_ok=True)
        for name, text in texts.items():
            (out_dir / name).write_text(text, encoding='utf-8')
            print(f'wrote {out_dir / name} ({len(text)} bytes)')
    return 0


