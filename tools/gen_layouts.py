"""Generate nordconv's data modules from opennord's TypeScript tables.

Why a generator: the converter must run on the Python standard library alone,
without Node, yet the field layouts and display tables are large and come from
opennord (AGPL-3.0-or-later) and, through it, ns4decode (MIT). Parsing the
TypeScript literals here keeps the Python data an exact, reproducible copy, so
a newer opennord commit can be picked up by re-running this script.

Usage:
    python3 -I tools/gen_layouts.py <path to an opennord checkout> [--out nordconv]

Writes nordconv/_layout_ns3.py, _layout_ns4.py, _tables_ns3.py and
_tables_ns4.py, and the TypeScript data modules of the web engine
(web/src/engine/generated/layout-ns3.ts, layout-ns4.ts, tables-ns3.ts and
tables-ns4.ts; --ts-out moves them). The opennord checkout is only read.
"""
