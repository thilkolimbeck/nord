#!/usr/bin/env python3
"""Golden files for the web engine's parity test, made by the Python reference converter.

The TypeScript engine (web/src/engine) must produce the same bytes, warnings, notes and error
messages as nordconv for every fixture. This script runs nordconv on every .ns3f under
web/test/fixtures and writes web/test/golden/golden.json:

    {"reference": <base64, 868 bytes>,
     "messages": [<every distinct warning and note, sorted>],
     "fixtures": {<path under web/test/fixtures>: {
         "sha256": <input file>,
         "patch": [[offset, <hex bytes>], ...],  # expected output = reference with these runs replaced
         "warnings": [<index into messages>, ...], "notes": [...]}
       or {"sha256": <input file>, "error": {"type": "NordFileError", "message": ...}}},
     "cases": {<name>: {"input": <base64>, ...the same fields as a fixture}}}

"cases" are inputs this script builds from one viewer fixture (CASE_BASE) and the donor
template: damaged files (bad magic, wrong tag, bad checksums, truncations, a broken block chain,
versions out of range) for the engine's error tests, and edge cases the viewer fixtures miss
(legacy container, format 3.00 delay fix-ups, an unknown category, rounding ties).

Private sample: the sample program pair under presets/ is kept out of the public repository
(presets/, web/test/fixtures/presets/ and web/test/golden/golden-local.json are gitignored).
When presets/stage3 holds .ns3f files, they are copied to web/test/fixtures/presets/ and their
expected results go to web/test/golden/golden-local.json, a self-contained manifest of the same
shape (own reference and messages, no cases). golden.json never depends on them, so it is the
same with or without the private files.

Storage: the viewer fixtures are variations of a few programs, so the expected outputs share
most bytes and most messages. "reference" holds, at every offset, the byte most expected
outputs have there (it is not itself a valid file, only the base the patches apply to), and
each output is stored as the byte runs where it differs; each message is stored once. That
keeps the manifest near 300 KB instead of about 2 MB for full outputs and inline messages.

It also writes web/src/engine/generated/template-bytes.ts, the bundled donor program as base64,
because the golden outputs depend on exactly that donor.

Usage:
    python3 -I tools/make_golden.py [--viewer <ns3-program-viewer checkout>]

--viewer first copies the viewer's test/ns3/**/*.ns3f fixtures (and its GPL-3 LICENSE) into
web/test/fixtures/ns3, keeping relative paths. Inputs (the viewer checkout, presets/) are only read.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import shutil
import sys
from collections import Counter
from dataclasses import replace
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))  # isolated mode (-I) leaves the repository off sys.path

from nordconv.bits import write_bits  # noqa: E402
from nordconv.cbin import FORMAT_LEGACY, NordFileError, build_cbin, parse_cbin  # noqa: E402
from nordconv.layout import NS3_LAYOUT  # noqa: E402
from nordconv.map_engines import HASH_OFFSET  # noqa: E402
from nordconv.convert import ConversionError, convert_bytes  # noqa: E402
from nordconv.template import TEMPLATE_PATH, load_template  # noqa: E402

WEB = ROOT / 'web'
FIXTURES = WEB / 'test' / 'fixtures'
GOLDEN = WEB / 'test' / 'golden' / 'golden.json'
GOLDEN_LOCAL = WEB / 'test' / 'golden' / 'golden-local.json'
TEMPLATE_TS = WEB / 'src' / 'engine' / 'generated' / 'template-bytes.ts'
#: The viewer fixture the synthetic cases are built from (format 3.04, NSM-era container).
CASE_BASE = FIXTURES / 'ns3' / 'global' / 'panelB.output.main.value eq 1-2.ns3f'
#: The private sample programs (gitignored) and their local copies under the fixtures.
PRIVATE_NS3 = ROOT / 'presets' / 'stage3'
LOCAL_FIXTURES = FIXTURES / 'presets'

TEMPLATE_HEADER = '''\
// GENERATED by tools/make_golden.py from templates/regressionTest.ns4p.
// Do not edit by hand; run `npm run gen` (or python3 -I tools/make_golden.py) instead.
//
// The donor program every output is patched into: ns4decode's regression fixture, by Randy
// (MIT; Copyright (c) 2024 Randy, Copyright (c) 2025 guyd789 (Nord User Forum) & Randy).
// The MIT notice is in NOTICE at the repository root.
'''


def copy_viewer_fixtures(viewer: Path) -> int:
    src_root = viewer / 'test' / 'ns3'
    dst_root = FIXTURES / 'ns3'
    files = sorted(p for p in src_root.rglob('*') if p.is_file() and p.suffix.lower() == '.ns3f')
    for src in files:
        dst = dst_root / src.relative_to(src_root)
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dst)
    shutil.copyfile(viewer / 'LICENSE', dst_root / 'LICENSE-ns3-program-viewer')
    return len(files)


def copy_private_samples() -> int:
    """Copy presets/stage3/*.ns3f (the private sample programs, if present) to the local fixtures."""
    files = sorted(PRIVATE_NS3.glob('*.ns3f')) if PRIVATE_NS3.is_dir() else []
    for src in files:
        LOCAL_FIXTURES.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, LOCAL_FIXTURES / src.name)
    return len(files)


def is_local(path: str) -> bool:
    """True for a fixture path (relative to web/test/fixtures) that belongs to the private sample."""
    return path.startswith(LOCAL_FIXTURES.name + '/')


def variant(changes: Dict[str, int], version: Optional[int] = None, **header: Any) -> bytes:
    """CASE_BASE with field values (and optionally the format version or header fields) changed."""
    parsed = parse_cbin(CASE_BASE.read_bytes(), 'ns3f')
    body = bytearray(parsed.body)
    for key, value in changes.items():
        f = NS3_LAYOUT.fields[key]
        write_bits(body, f.body_bit, f.width, f.encode(value))
    if version is not None:
        body[0:4] = version.to_bytes(4, 'big')
        header['version'] = version
    return build_cbin(replace(parsed.header, **header), bytes(body))


def stage3_hash(ns4_hash: int) -> int:
    """The Stage 3 encoding of a Stage 4 name hash (the inverse of map_engines.ns4_hash)."""
    return (ns4_hash - HASH_OFFSET) & 0xFFFFFFFF


def build_cases() -> Dict[str, bytes]:
    """Damaged and edge-case inputs, built from CASE_BASE (and the donor template for a wrong tag)."""
    sample = CASE_BASE.read_bytes()
    parsed = parse_cbin(sample, 'ns3f')
    flipped = bytearray(sample)
    flipped[-1] ^= 0xFF
    legacy = build_cbin(replace(parsed.header, format_type=FORMAT_LEGACY), parsed.body)
    legacy_bad = bytearray(legacy)
    legacy_bad[30] ^= 0x01
    chain = bytearray(parsed.body)
    chain[4] -= 1  # the first block claims one byte less: the chain no longer matches the layout
    odd_tag = bytearray(sample)
    odd_tag[8:12] = b"\xa0'\x01 "
    unsupported = bytearray(sample)
    unsupported[4:8] = (7).to_bytes(4, 'little')
    synth_a = {'common.slotEnable': 1, 'synthCommonA.enable': 1}
    # A valid format 3.00 delay: rate 0-127 and every morph delta at the 3.00 zero, on both panels.
    zero = 127 - 16383
    os300 = {f'effects{p}.{k}': v for p in 'AB' for k, v in
             (('dlyRateClkDiv', 20), ('dlyRateClkDiv.morphWheel', zero), ('dlyRateClkDiv.morphAfterTouch', zero),
              ('dlyRateClkDiv.morphCtrlPedal', zero))}
    return {
        'bad magic': b'XBIN' + sample[4:],
        'wrong tag (a Stage 4 program)': TEMPLATE_PATH.read_bytes(),
        'odd tag characters': bytes(odd_tag),
        'bad CRC-32': bytes(flipped),
        'empty file': b'',
        'truncated inside the CBIN header': sample[:20],
        'truncated inside the NSM-era header': sample[:30],
        'truncated body (stale CRC)': sample[:300],
        'truncated body (resealed)': build_cbin(parsed.header, parsed.body[:256]),
        'unsupported formatType': bytes(unsupported),
        'legacy container': legacy,
        'legacy container with a bad CRC-16': bytes(legacy_bad),
        'broken block chain': build_cbin(parsed.header, bytes(chain)),
        'format version below the range': variant({}, version=299),
        'format version above the range': variant({}, version=305),
        'format 3.00, delay rate refused': variant({**os300, 'effectsA.dlyRateClkDiv': 200}, version=300),
        'format 3.00, delay morph refused': variant({**os300, 'effectsA.dlyRateClkDiv': 10,
                                                     'effectsA.dlyRateClkDiv.morphWheel': zero + 200},
                                                    version=300),
        'format 3.00, synced delay': variant({**os300, 'effectsA.dlyRateClkDiv': 64, 'effectsA.dlyClkEnable': 1,
                                              'effectsA.dlyEnable': 1, 'effectsA.dlyRateClkDiv.morphWheel': zero + 10,
                                              'effectsA.dlyRateClkDiv.morphAfterTouch': zero + 63,
                                              'effectsA.dlyRateClkDiv.morphCtrlPedal': zero - 64},
                                             version=300),
        'format 3.00, free-running delay': variant({**os300, 'effectsA.dlyRateClkDiv': 64,
                                                    'effectsA.dlyClkEnable': 0,
                                                    'effectsA.dlyRateClkDiv.morphWheel': zero - 5},
                                                   version=300),
        'format 3.01, dual keyboard style': variant({'common.dualKbdEnable': 1, 'common.dualKbdStyle': 0},
                                                    version=301),
        'unknown category': variant({}, category=99),
        'rounding ties (fltMod +30, oscMod -30)': variant({**synth_a, 'synthA.fltMod': 30, 'synthA.oscMod': -30}),
        'filter velocity amount (fltMod -45)': variant({**synth_a, 'synthA.fltMod': -45}),
        'filter velocity amount (fltMod -3)': variant({**synth_a, 'synthA.fltMod': -3}),
        # Rules from three Nord Sound Manager conversions that the viewer fixtures miss.
        'Sample oscillator with a named Stage 4 sample': variant({**synth_a, 'synthA.oscBank': 4,
                                                                  'synthA.smpNameHash': stage3_hash(0x002EBCAA),
                                                                  'synthA.oscConf': 4, 'synthA.dualOscDetune': 0,
                                                                  'synthA.oscCtrl': 5}),
        'substituted piano with an entry, piano off': variant({'common.slotEnable': 1, 'pianoA.enable': 0,
                                                               'pianoA.nameHash': stage3_hash(0xB54A2C61),
                                                               'pianoA.entry': 3}),
        'extern CC sent on load': variant({'common.slotEnable': 1, 'externA.enable': 1, 'externA.paramSelect': 0,
                                           'externA.ccNumber': 7, 'externA.ccValue': 9, 'externA.sendOnLoadCC': 1}),
    }


def patch_runs(base: bytes, data: bytes) -> List[Tuple[int, str]]:
    """The byte runs where `data` differs from `base` (same length), as (offset, hex)."""
    if len(base) != len(data):
        raise SystemExit(f'output is {len(data)} bytes, the base {len(base)}')
    runs: List[Tuple[int, str]] = []
    i = 0
    while i < len(data):
        if data[i] == base[i]:
            i += 1
            continue
        start = i
        while i < len(data) and data[i] != base[i]:
            i += 1
        runs.append((start, data[start:i].hex()))
    return runs


def run(data: bytes, template: Any) -> Dict[str, Any]:
    """The Python converter's result for one input: output bytes and messages, or the error."""
    try:
        converted = convert_bytes(data, template)
    except (NordFileError, ConversionError, ValueError, AssertionError, KeyError) as exc:
        return {'error': {'type': type(exc).__name__, 'message': str(exc)}}
    return {'data': converted.data, 'warnings': list(converted.warnings), 'notes': list(converted.notes)}


def consensus(outputs: List[bytes], size: int) -> bytes:
    """At every offset the most common byte (ties: the smallest value), so patches stay short."""
    if not outputs:
        return bytes(size)
    return bytes(max(sorted(Counter(o[i] for o in outputs).items()), key=lambda kv: kv[1])[0] for i in range(size))


def write_template_ts() -> None:
    encoded = base64.b64encode(TEMPLATE_PATH.read_bytes()).decode('ascii')
    lines = [TEMPLATE_HEADER, '/** templates/regressionTest.ns4p, base64. */', 'export const TEMPLATE_BASE64 =']
    chunks = [encoded[i:i + 100] for i in range(0, len(encoded), 100)]
    lines += [f"  '{chunk}'" + (' +' if n < len(chunks) - 1 else ';') for n, chunk in enumerate(chunks)]
    TEMPLATE_TS.parent.mkdir(parents=True, exist_ok=True)
    TEMPLATE_TS.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'wrote {TEMPLATE_TS.relative_to(ROOT)}')


def write_manifest(path: Path, results: Dict[str, Tuple[bytes, Dict[str, Any]]],
                   case_results: Dict[str, Tuple[bytes, Dict[str, Any]]], size: int) -> str:
    """Write one golden manifest (its own reference and messages) and return a summary line."""
    everything = list(results.values()) + list(case_results.values())
    reference = consensus([r['data'] for _, r in results.values() if 'data' in r], size)
    messages = sorted({m for _, r in everything for m in r.get('warnings', []) + r.get('notes', [])})
    index = {m: n for n, m in enumerate(messages)}

    def entry_for(data: bytes, r: Dict[str, Any], key: str, key_value: str) -> Dict[str, Any]:
        entry: Dict[str, Any] = {key: key_value}
        if 'error' in r:
            entry['error'] = r['error']
        else:
            entry['patch'] = patch_runs(reference, r['data'])
            entry['warnings'] = [index[m] for m in r['warnings']]
            entry['notes'] = [index[m] for m in r['notes']]
        return entry

    fixtures = {p: entry_for(data, r, 'sha256', hashlib.sha256(data).hexdigest()) for p, (data, r) in results.items()}
    cases = {name: entry_for(data, r, 'input', base64.b64encode(data).decode('ascii'))
             for name, (data, r) in case_results.items()}
    errors = sum('error' in e for e in fixtures.values())
    dump = lambda obj: json.dumps(obj, ensure_ascii=False)  # noqa: E731
    lines = ['{',
             '  "generator": "tools/make_golden.py",',
             '  "template": "templates/regressionTest.ns4p",',
             f'  "reference": {dump(base64.b64encode(reference).decode("ascii"))},',
             '  "messages": [']
    lines += [f'    {dump(m)}' + (',' if n < len(messages) - 1 else '') for n, m in enumerate(messages)]
    lines += ['  ],', '  "fixtures": {']
    items = list(fixtures.items())
    lines += [f'    {dump(p)}: {dump(entry)}' + (',' if n < len(items) - 1 else '')
              for n, (p, entry) in enumerate(items)]
    lines += ['  },', '  "cases": {']
    items = list(cases.items())
    lines += [f'    {dump(name)}: {dump(entry)}' + (',' if n < len(items) - 1 else '')
              for n, (name, entry) in enumerate(items)]
    lines += ['  }', '}', '']
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text('\n'.join(lines), encoding='utf-8')
    return (f'wrote {path.relative_to(ROOT)}: {len(fixtures)} fixtures ({errors} refused), '
            f'{len(cases)} cases ({sum("error" in e for e in cases.values())} refused)')


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--viewer', type=Path, help='ns3-program-viewer checkout to copy the fixtures from first')
    args = ap.parse_args(argv)
    if args.viewer:
        print(f'copied {copy_viewer_fixtures(args.viewer)} fixtures from {args.viewer}')
    private = copy_private_samples()
    write_template_ts()
    template = load_template()
    size = len(template.to_bytes())
    inputs = sorted(p for p in FIXTURES.rglob('*') if p.is_file() and p.suffix.lower() == '.ns3f')
    results = {p.relative_to(FIXTURES).as_posix(): (p.read_bytes(), run(p.read_bytes(), template)) for p in inputs}
    public = {k: v for k, v in results.items() if not is_local(k)}
    local = {k: v for k, v in results.items() if is_local(k)}
    if not public:
        raise SystemExit(f'no .ns3f fixtures under {FIXTURES} (run once with --viewer)')
    case_results = {name: (data, run(data, template)) for name, data in build_cases().items()}
    print(write_manifest(GOLDEN, public, case_results, size))
    if local:
        print(write_manifest(GOLDEN_LOCAL, local, {}, size) + f' (private, gitignored; {private} copied from presets/)')
    else:
        print(f'no private sample under {LOCAL_FIXTURES.relative_to(ROOT)}: {GOLDEN_LOCAL.relative_to(ROOT)} not written')
    return 0


if __name__ == '__main__':
    sys.exit(main())
